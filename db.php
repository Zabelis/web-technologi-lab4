<?php
// Настройки подключения к базе данных
$host = 'localhost'; // Хост базы данных (чаще всего localhost)
$username = 'root'; // Имя пользователя базы данных
$password = ''; // Пароль базы данных
$dbname = 'game_store'; // Название базы данных

// Устанавливаем соединение с базой данных
$conn = mysqli_connect($host, $username, $password, $dbname);

// Проверка на успешное подключение
if (!$conn) {
    die("Ошибка подключения к базе данных: " . mysqli_connect_error());
}

// Устанавливаем кодировку соединения для корректной работы с русскими символами
mysqli_set_charset($conn, "utf8");

// Возвращаем соединение для использования в других частях приложения
?>
